/* =====================================================
   CURRENT BOOK
===================================================== */

let currentChapter = 1;


/* =====================================================
   OPEN BOOK
===================================================== */

function openBook(number) {

    currentChapter = number;

    const overlay =
        document.getElementById("bookOverlay");

    const realBook =
        document.getElementById("realBook");

    const cover =
        document.getElementById("bookCover");


    /* Reset animation */

    realBook.style.transform =
        "scale(.75) translateY(80px)";


    cover.style.transform =
        "rotateY(0deg)";


    overlay.classList.add("active");


    document.body.style.overflow =
        "hidden";


    updateBook();


    /* Buku masuk ke tengah */

    setTimeout(() => {

        realBook.style.transform =
            "scale(1) translateY(0)";

    }, 100);


    /* Sampul terbuka */

    setTimeout(() => {

        cover.style.transform =
            "rotateY(-180deg)";

    }, 700);

}


/* =====================================================
   CLOSE BOOK
===================================================== */

function closeBook() {

    const overlay = document.getElementById("bookOverlay");
    const realBook = document.getElementById("realBook");
    const cover = document.getElementById("bookCover");

    // Tutup kembali sampul
    cover.style.transform = "rotateY(0deg)";

    // Sedikit mengecil saat buku ditutup
    realBook.style.transform =
        "scale(0.75) translateY(80px)";

    // Tunggu animasi selesai
    setTimeout(() => {

        overlay.classList.remove("active");

        document.body.style.overflow = "auto";

        // Reset posisi buku
        realBook.style.transform =
            "scale(1) translateY(0)";

        // Reset halaman
        currentPage = 1;

    }, 1000);
}


/* =====================================================
   UPDATE BOOK CONTENT
===================================================== */

function updateBook() {

    const chapter =
        chapters[currentChapter];


    document.getElementById(
        "leftContent"
    ).innerHTML = chapter.left;


    document.getElementById(
        "rightContent"
    ).innerHTML = chapter.right;


    document.getElementById(
        "chapterTitle"
    ).textContent = chapter.title;


    document.getElementById(
        "coverNumber"
    ).textContent =
        chapter.coverNumber;


    document.getElementById(
        "coverTitle"
    ).innerHTML =
        chapter.coverTitle;


    document.getElementById(
        "leftNumber"
    ).textContent =
        chapter.coverNumber;


    document.getElementById(
        "rightNumber"
    ).textContent =
        chapter.coverNumber;

}


/* =====================================================
   NEXT BOOK
===================================================== */

function nextPage() {

    currentPage++;

    if (currentPage > 3) {
        currentPage = 1;
    }

    flipBookPage();
}


/* =====================================================
   PREVIOUS BOOK
===================================================== */

function previousPage() {

    currentPage--;

    if (currentPage < 1) {
        currentPage = 3;
    }

    flipBookPage();
}
function flipBookPage() {

    const inside =
        document.querySelector(".book-inside");

    inside.style.transform =
        "scale(.95) rotateY(8deg)";

    setTimeout(() => {

        inside.style.transform =
            "scale(1) rotateY(0deg)";

    }, 300);
}

/* =====================================================
   CLICK OUTSIDE
===================================================== */

document
    .getElementById("bookOverlay")
    .addEventListener(
        "click",
        function(event) {

            if (
                event.target === this
            ) {

                closeBook();

            }

        }
    );


/* =====================================================
   KEYBOARD
===================================================== */

document.addEventListener(
    "keydown",
    function(event) {

        if (
            event.key === "Escape"
        ) {

            closeBook();

        }


        if (
            event.key === "ArrowRight"
        ) {

            nextPage();

        }


        if (
            event.key === "ArrowLeft"
        ) {

            previousPage();

        }

    }
);
